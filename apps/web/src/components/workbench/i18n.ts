const messages: Record<Locale, Record<WorkbenchMessageKey, string>> = {
  "zh-Hant": zhHant,
  "zh-Hans": zhHans,
  en,
};

export function getWorkbenchMessage(
  locale: Locale,
  key: WorkbenchMessageKey,
): string {
  return messages[locale][key];
}

export function useWorkbenchLocale() {
  const { locale } = useLocale();
  return {
    locale,
    t: (key: WorkbenchMessageKey) => getWorkbenchMessage(locale, key),
  };
}

export function localizedWorkbenchText(
  locale: Locale,
  text: { en?: string; zhHans?: string; zhHant?: string },
): string {
  const selected =
    locale === "zh-Hant"
      ? text.zhHant
      : locale === "zh-Hans"
        ? text.zhHans
        : text.en;
  return selected ?? text.en ?? text.zhHant ?? text.zhHans ?? "";
}
